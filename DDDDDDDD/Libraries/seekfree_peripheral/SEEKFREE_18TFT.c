//液晶字符输出(16*12字体)
//x: 0 - 7  (列)
//y: 0 -12  (行)
void TFTSPI_P16x12Str(unsigned char x,unsigned char y,unsigned char *s_dat,unsigned int word_color,unsigned int back_color)
{
 unsigned char wm=0,ii = 0,i,j;
 unsigned int adder=1;

 while(s_dat[ii] != '\0')
 {
   wm = 0;
   adder = 1;
   while(hanzi_16_12Idx[wm] > 127)
   {
     if(hanzi_16_12Idx[wm] == s_dat[ii])
     {
       if(hanzi_16_12Idx[wm + 1] == s_dat[ii + 1])
       {
         adder = wm * 12;
         break;
       }
     }
     wm += 2;
   }

   if(adder != 1)// 显示汉字
   {
       lcd_set_region(x*16,y*12,(x+1)*16-1,(y+1)*12-1);          //定位字符显示区域
     for(j=0; j <24; j++)
     {
       for(i=0; i<8; i++)
       {
         if((hanzi[adder]) &  (0x80>>i))     //////
             lcd_writedata_16bit(word_color);
         else
             lcd_writedata_16bit(back_color);
       }
       adder += 1;
     }
   }
   else              //显示空白字符
   {}
   //y+=1;//左右方向
   x+=1;//上下方向
   ii += 2;
 }

}


